#!/usr/bin/env python3
"""Validate the case ledger and generate its C registry (no network access)."""
import argparse
import hashlib
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parent.parent

def generate():
    raw = (ROOT / 'requirements.json').read_bytes()
    cases = json.loads(raw)['cases']
    # Scan implementation headers as well as the entry point, but never the
    # generated registry: its references cannot prove a function exists.
    sources = [ROOT / 'main.c', ROOT / 'conformance_tests.h']
    sources += sorted(p for p in ROOT.glob('test_*.h')
                      if p.name != 'test_cases.h')
    source = '\n'.join(p.read_text() for p in sources)
    ids = set()
    rows = []
    for c in cases:
        assert re.fullmatch(r'[A-Z0-9-]+', c['id']) and c['id'] not in ids, c['id']
        ids.add(c['id'])
        assert re.search(r'\b' + re.escape(c['function']) + r'\s*\(', source), c['function']
        assert c['strength'] in ('MUST', 'SHOULD', 'MAY', 'PROFILE')
        assert c['profile'] in ('base', 'tfo', 'strict-api', 'blake2', 'regression')
        assert c['coverage'] in ('partial', 'planned-complete')
        for key in ('requirement_id','source','applicability','responsibility','oracle','gaps'):
            assert isinstance(c[key],str) and c[key].strip(), (c['id'],key)
        fields = [json.dumps(c[k]) for k in ('id','description','requirement_id','source','strength','profile','coverage')]
        rows.append('    { ' + c['function'] + ', ' + ', '.join(fields) + ' },')
    assert {f'MUST-{i}' for i in range(1,70)} <= ids
    return ('/* Generated by scripts/generate_cases.py; edit requirements.json. */\n'
            '#define TEST_LEDGER_SHA256 "' + hashlib.sha256(raw).hexdigest() + '"\n'
            'static const struct test_case test_cases[] = {\n' + '\n'.join(rows) + '\n};\n')

def main():
    p=argparse.ArgumentParser(); p.add_argument('--check',action='store_true'); args=p.parse_args()
    text=generate(); dest=ROOT/'test_cases.h'
    if args.check:
        assert dest.read_text()==text, 'stale test_cases.h; run make registry'
    else:
        dest.write_text(text)

if __name__=='__main__': main()
